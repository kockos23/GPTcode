import { defineSchema, defineTable } from "convex/server"
import { v } from "convex/values"
import { authTables } from "@convex-dev/auth/server"

export default defineSchema({
  ...authTables,
  users: defineTable({
    name: v.optional(v.string()),
    image: v.optional(v.string()),
    email: v.optional(v.string()),
    emailVerificationTime: v.optional(v.number()),
    phone: v.optional(v.string()),
    phoneVerificationTime: v.optional(v.number()),
    isAnonymous: v.optional(v.boolean()),
    googleSubject: v.optional(v.string()),
  })
    .index("email", ["email"])
    .index("google_subject", ["googleSubject"]),
  wofFinanceCache: defineTable({
    cacheKey: v.string(),
    rows: v.array(v.object({
      id: v.string(),
      kind: v.string(),
      documentStatus: v.string(),
      supplier: v.string(),
      invoiceNumber: v.string(),
      dueDate: v.string(),
      amount: v.string(),
      currency: v.string(),
      paymentMethod: v.string(),
      paymentStatus: v.string(),
      transactionId: v.string(),
      fileUrl: v.string(),
      note: v.string(),
      paidAmount: v.optional(v.string()),
      paymentHistory: v.optional(v.string()),
    })),
    updatedAt: v.number(),
  }).index("by_cache_key", ["cacheKey"]),
  bankStatements: defineTable({
    sourceFileId: v.string(),
    sourceFileName: v.string(),
    sourceFileUrl: v.string(),
    pdfFileId: v.optional(v.string()),
    pdfFileName: v.optional(v.string()),
    accountKey: v.string(),
    accountLabel: v.string(),
    currency: v.string(),
    accountNumberMasked: v.string(),
    statementNumber: v.string(),
    periodStart: v.string(),
    periodEnd: v.string(),
    openingBalance: v.number(),
    closingBalance: v.number(),
    incomeTotal: v.number(),
    expenseTotal: v.number(),
    transactionCount: v.number(),
    duplicateCount: v.number(),
    importedAt: v.number(),
    status: v.string(),
  }).index("by_source_account", ["sourceFileId", "accountKey"])
    .index("by_source_file", ["sourceFileId"])
    .index("by_imported_at", ["importedAt"]),
  bankTransactions: defineTable({
    statementId: v.id("bankStatements"),
    accountKey: v.string(),
    operationId: v.string(),
    bookedOn: v.string(),
    amount: v.number(),
    currency: v.string(),
    counterpartyAccount: v.string(),
    counterpartyName: v.string(),
    bankName: v.string(),
    constantSymbol: v.string(),
    variableSymbol: v.string(),
    specificSymbol: v.string(),
    note: v.string(),
    recipientMessage: v.string(),
    transactionType: v.string(),
    bic: v.string(),
    instructionId: v.string(),
    matchStatus: v.string(),
    matchedPayableId: v.string(),
    matchScore: v.optional(v.number()),
    matchReason: v.optional(v.string()),
  }).index("by_account_operation", ["accountKey", "operationId"])
    .index("by_operation", ["operationId"])
    .index("by_statement", ["statementId"])
    .index("by_booked_on", ["bookedOn"]),
  wofFinanceEmailImports: defineTable({
    gmailKey: v.string(),
    messageId: v.string(),
    attachmentId: v.string(),
    fileName: v.string(),
    sender: v.string(),
    subject: v.string(),
    receivedAt: v.number(),
    status: v.string(),
    driveFileId: v.optional(v.string()),
    driveUrl: v.optional(v.string()),
    category: v.optional(v.string()),
    deliveryDate: v.optional(v.string()),
    routingEvidence: v.optional(v.string()),
    reviewReason: v.optional(v.string()),
    error: v.optional(v.string()),
    updatedAt: v.number(),
  }).index("by_gmail_key", ["gmailKey"])
    .index("by_updated_at", ["updatedAt"])
    .index("by_status", ["status"]),
  wofFinanceIntakeRuns: defineTable({
    startedAt: v.number(),
    completedAt: v.optional(v.number()),
    status: v.string(),
    checkedEmails: v.number(),
    savedFiles: v.number(),
    skippedFiles: v.number(),
    failedFiles: v.number(),
    reviewFiles: v.optional(v.number()),
    error: v.optional(v.string()),
    trigger: v.string(),
  }).index("by_started_at", ["startedAt"]),
  financeDocumentReviews: defineTable({
    documentId: v.string(),
    source: v.string(),
    sourceFileId: v.string(),
    sourceFileName: v.string(),
    fileUrl: v.string(),
    supplier: v.string(),
    invoiceNumber: v.string(),
    totalAmount: v.optional(v.number()),
    extractedDeliveryDate: v.optional(v.string()),
    extractedCategory: v.optional(v.string()),
    extractedCurrency: v.optional(v.string()),
    reviewReason: v.string(),
    status: v.string(),
    resolvedDeliveryDate: v.optional(v.string()),
    resolvedCategory: v.optional(v.string()),
    resolvedCurrency: v.optional(v.string()),
    resolutionNote: v.optional(v.string()),
    resolvedBy: v.optional(v.string()),
    resolvedAt: v.optional(v.number()),
    completedAt: v.optional(v.number()),
    completionError: v.optional(v.string()),
    targetFileId: v.optional(v.string()),
    targetFileUrl: v.optional(v.string()),
    createdAt: v.number(),
    updatedAt: v.number(),
  })
    .index("by_document_id", ["documentId"])
    .index("by_status", ["status"])
    .index("by_updated_at", ["updatedAt"]),
  financeRegisterCommands: defineTable({
    commandId: v.string(),
    type: v.string(),
    payload: v.any(),
    status: v.string(),
    createdBy: v.string(),
    createdAt: v.number(),
    updatedAt: v.number(),
    attempts: v.optional(v.number()),
    processedAt: v.optional(v.number()),
    resultMessage: v.optional(v.string()),
    error: v.optional(v.string()),
  })
    .index("by_command_id", ["commandId"])
    .index("by_status", ["status"])
    .index("by_created_at", ["createdAt"]),
  billduDocumentImports: defineTable({
    sourceDocumentId: v.string(),
    sourceVersion: v.string(),
    invoiceNumber: v.string(),
    deliveryDate: v.string(),
    currency: v.string(),
    totalAmount: v.number(),
    status: v.string(),
    attempts: v.number(),
    leaseUntil: v.optional(v.number()),
    driveFileId: v.optional(v.string()),
    driveFileUrl: v.optional(v.string()),
    registerDocumentId: v.optional(v.string()),
    error: v.optional(v.string()),
    createdAt: v.number(),
    updatedAt: v.number(),
    completedAt: v.optional(v.number()),
  })
    .index("by_source_document", ["sourceDocumentId"])
    .index("by_status", ["status"])
    .index("by_updated_at", ["updatedAt"]),
})
